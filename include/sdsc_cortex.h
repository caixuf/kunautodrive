    if (SDSC_UNLIKELY(!ctx)) return;
    memset(ctx, 0, sizeof(SdscCortex));
    ctx->cell_count    = SDSC_CELL_COUNT;
    ctx->synapse_count = SDSC_SYNAPSE_COUNT;
    ctx->input_count   = SDSC_IN_DIM;
    ctx->output_count  = SDSC_OUT_DIM;
